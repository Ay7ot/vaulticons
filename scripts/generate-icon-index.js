const fs = require('fs');
const path = require('path');

// Adjust path relative to the script location
const coreDir = path.resolve(__dirname, '../packages/core');
const iconsDir = path.join(coreDir, 'src/icons');
const indexPath = path.join(iconsDir, 'index.ts');
const wrapperPath = path.join(coreDir, 'src/createIcon'); // Path to the wrapper

// Convert to relative path for import statement
const relativeWrapperPath = path.relative(iconsDir, wrapperPath).replace(/\\/g, '/');

console.log(`Looking for icons in: ${iconsDir}`);

let indexContent = `// This file is auto-generated by scripts/generate-icon-index.js
// Do not edit this file manually!

import { createIcon } from '${relativeWrapperPath}'; // Import the wrapper
import type { IconProps } from '${relativeWrapperPath}'; // Import the props type

`;

fs.readdir(iconsDir, (err, files) => {
    if (err) {
        console.error('Error reading icons directory:', err);
        process.exit(1);
    }

    const iconFiles = files.filter(
        (file) => file.endsWith('.tsx') && file !== 'index.ts'
    );

    console.log(`Found ${iconFiles.length} icon components.`);

    let exportsContent = '';
    if (iconFiles.length === 0) {
        console.log('No icon components found, writing empty exports.');
        exportsContent += '// No icons found\n';
    } else {
        iconFiles.forEach((file) => {
            const componentName = path.basename(file, '.tsx');
            const exportName = `${componentName}Icon`; // Append 'Icon' suffix
            // Import the original SVG component and wrap it
            indexContent += `import ${componentName}Svg from './${componentName}';\n`;
            exportsContent += `export const ${exportName} = createIcon(${componentName}Svg);\n`;
        });
    }

    // Add the IconProps export
    exportsContent += `\nexport type { IconProps };\n`;

    // Combine imports and exports
    indexContent += `\n${exportsContent}`;

    fs.writeFile(indexPath, indexContent, (err) => {
        if (err) {
            console.error('Error writing index.ts:', err);
            process.exit(1);
        }
        console.log(`Successfully generated ${indexPath}`);
    });
}); 